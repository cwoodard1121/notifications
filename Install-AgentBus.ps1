function Add-Result([string]$Target, [string]$Result, [string]$Detail) {
    $Report.Add([pscustomobject]@{ Target = $Target; Result = $Result; Detail = $Detail })
}

function Format-Arg([string]$Value) {
    if ($Value -eq '') { return '""' }
    if ($Value -notmatch '[\s"]') { return $Value }
    $escaped = $Value -replace '(\\*)"', '$1$1\"'
    $escaped = $escaped -replace '(\\+)$', '$1$1'
    return '"' + $escaped + '"'
}

function Invoke-Native {
    # Runs a program with captured output, closed stdin (no interactive prompts) and an optional CLAUDE_CONFIG_DIR that
    # exists only in the child's environment. Never kills anything: a timeout is reported and the child left alone.
    param([string]$Exe, [string[]]$Arguments, [string]$ConfigDir, [string]$StdIn, [int]$TimeoutSec = 180)
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $argLine = (@($Arguments) | ForEach-Object { Format-Arg $_ }) -join ' '
    if ($Exe -match '\.(cmd|bat)$') {
        $psi.FileName = $env:ComSpec
        $psi.Arguments = '/d /s /c "' + (Format-Arg $Exe) + ' ' + $argLine + '"'
    } else {
        $psi.FileName = $Exe
        $psi.Arguments = $argLine
    }
    $psi.UseShellExecute = $false
    $psi.CreateNoWindow = $true
    $psi.RedirectStandardInput = $true
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $psi.StandardOutputEncoding = [System.Text.Encoding]::UTF8
    $psi.StandardErrorEncoding = [System.Text.Encoding]::UTF8
    $psi.WorkingDirectory = $Root
    foreach ($name in $SessionVars) {
        if ($psi.EnvironmentVariables.ContainsKey($name)) { $psi.EnvironmentVariables.Remove($name) }
    }
    if ($ConfigDir) { $psi.EnvironmentVariables['CLAUDE_CONFIG_DIR'] = $ConfigDir }
    $process = [System.Diagnostics.Process]::Start($psi)
    $stdout = $process.StandardOutput.ReadToEndAsync()
    $stderr = $process.StandardError.ReadToEndAsync()
    if ($StdIn) { $process.StandardInput.Write($StdIn) }
    $process.StandardInput.Close()
    if (-not $process.WaitForExit($TimeoutSec * 1000)) {
        return [pscustomobject]@{ Code = -1; Out = ''; Err = "timed out after $TimeoutSec s (left running, not killed)" }
    }
    $process.WaitForExit()
    return [pscustomobject]@{ Code = $process.ExitCode; Out = $stdout.Result; Err = $stderr.Result }
}

function First-Line([string]$Text) {
    $line = ($Text -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -First 1)
    if ($line) { return $line.Trim() } else { return '' }
}

function Invoke-Helper([string[]]$HelperArgs) {
    $result = Invoke-Native -Exe $script:Py -Arguments (@('-') + $HelperArgs) -StdIn $Helper -TimeoutSec 60
    $line = ($result.Out -split "`r?`n" | Where-Object { $_.Trim().StartsWith('{') } | Select-Object -Last 1)
    if (-not $line) { throw "helper '$($HelperArgs[0])' failed: $(First-Line ($result.Err + $result.Out))" }
    $data = $line | ConvertFrom-Json
    if (-not $data.ok) { throw "helper '$($HelperArgs[0])': $($data.error)" }
    return $data
}

function Dry { if ($DryRun) { '1' } else { '0' } }

$BackedUp = @{}
function Backup-File([string]$Path, [string]$Label) {
    # Once per file per run, so the backup is the state from before this run touched it.
    if ($DryRun -or -not (Test-Path -LiteralPath $Path) -or $BackedUp.ContainsKey($Path)) { return }
    $BackedUp[$Path] = $true
    New-Item -ItemType Directory -Path $BackupDir -Force | Out-Null
    $name = 'agentbus-{0}-{1}-{2}' -f $Label, $Stamp, (Split-Path $Path -Leaf)
    Copy-Item -LiteralPath $Path -Destination (Join-Path $BackupDir $name) -Force
}

function Copy-Skill([string]$Source, [string]$TargetDir, [string]$Label) {
    # Returns 'installed', 'updated', 'unchanged' (or 'would ...' in a dry run). Edited copies are backed up first.
    $target = Join-Path $TargetDir 'SKILL.md'
    if (Test-Path -LiteralPath $target) {
        if ((Get-FileHash -LiteralPath $target).Hash -eq (Get-FileHash -LiteralPath $Source).Hash) { return 'unchanged' }
        if ($DryRun) { return 'would update' }
        Backup-File $target $Label
        Copy-Item -LiteralPath $Source -Destination $target -Force
        return 'updated'
    }
    if ($DryRun) { return 'would install' }
    New-Item -ItemType Directory -Path $TargetDir -Force | Out-Null
    Copy-Item -LiteralPath $Source -Destination $target -Force
    return 'installed'
}

function Remove-SkillDir([string]$TargetDir, [string]$Label) {
    if (-not (Test-Path -LiteralPath $TargetDir)) { return 'not present' }
    if ($DryRun) { return 'would remove' }
    $skill = Join-Path $TargetDir 'SKILL.md'
    if (Test-Path -LiteralPath $skill) { Backup-File $skill $Label }
    Remove-Item -LiteralPath $TargetDir -Recurse -Force
    return 'removed'
}

function Resolve-Python {
    $candidates = @()
    if ($Python) { $candidates += $Python }
    foreach ($name in @('python', 'python3', 'py')) {
        foreach ($cmd in @(Get-Command $name -CommandType Application -All -ErrorAction SilentlyContinue)) {
            if ($cmd.Source -notlike '*\WindowsApps\*') { $candidates += $cmd.Source }
        }
    }
    $candidates += (Join-Path $env:LOCALAPPDATA 'Programs\Python\Python312\python.exe')
    foreach ($candidate in $candidates) {
        if (-not $candidate -or -not (Test-Path -LiteralPath $candidate)) { continue }
        $probe = Invoke-Native -Exe $candidate -Arguments @('-c', 'import sys; print(sys.executable); print(sys.version_info >= (3, 11))') -TimeoutSec 60
        $lines = @($probe.Out -split "`r?`n" | Where-Object { $_.Trim() })
        if ($probe.Code -eq 0 -and $lines.Count -ge 2 -and $lines[1].Trim() -eq 'True') { return $lines[0].Trim() }
    }
    throw 'Python 3.11+ not found. Pass -Python C:\path\to\python.exe'
}

function Get-ClaudeJson([string]$ConfigDir, [string[]]$Arguments) {
    $result = Invoke-Native -Exe $script:Claude -Arguments $Arguments -ConfigDir $ConfigDir -TimeoutSec 120
    if ($result.Code -ne 0) { throw "claude $($Arguments -join ' ') failed: $(First-Line ($result.Err + $result.Out))" }
    $text = $result.Out
    $start = $text.IndexOf('[')
    if ($start -lt 0) { return }
    # PS 5.1 hands a JSON array over as ONE object; emit the items so callers get a flat list.
    $parsed = ConvertFrom-Json -InputObject $text.Substring($start)
    foreach ($item in @($parsed)) { $item }
}

function Invoke-ClaudeStep([string]$ConfigDir, [string[]]$Arguments) {
    $result = Invoke-Native -Exe $script:Claude -Arguments $Arguments -ConfigDir $ConfigDir -TimeoutSec 180
    if ($result.Code -ne 0) { throw "claude $($Arguments -join ' ') failed: $(First-Line ($result.Err + $result.Out))" }
}

