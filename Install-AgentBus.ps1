# ------------------------------------------------------------------ study mailbox ACL
if ($Remove) {
    foreach ($dir in @($info.mailbox_dirs)) {
        $Notes.Add("Mailbox ACL left in place on $dir (revoke: icacls `"$dir`" /remove `"NT SERVICE\LocalNotify`").")
    }
} elseif (-not $info.mailbox_enabled -or -not @($info.mailbox_dirs).Count) {
    Add-Result 'study mailbox' 'skipped' 'bus.mailbox is disabled or has no dirs in config'
} else {
    $service = Get-Service -Name 'LocalNotify' -ErrorAction SilentlyContinue
    foreach ($dir in @($info.mailbox_dirs)) {
        try {
            if (-not $service) { throw 'the LocalNotify Windows service is not installed (run Install-Service.ps1 first)' }
            $parent = Split-Path -Parent $dir
            if (-not (Test-Path -LiteralPath $dir)) {
                if (-not (Test-Path -LiteralPath $parent)) { throw "parent folder $parent does not exist" }
                if (-not $DryRun) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
            }
            $acl = if (Test-Path -LiteralPath $dir) { Invoke-Native -Exe (Join-Path $env:SystemRoot 'System32\icacls.exe') -Arguments @($dir) -TimeoutSec 60 } else { $null }
            if ($acl -and $acl.Out -match 'NT SERVICE\\LocalNotify:\(OI\)\(CI\)\(M\)') {
                Add-Result 'study mailbox' 'ok' "Modify already granted on $dir"
            } elseif ($DryRun) {
                Add-Result 'study mailbox' 'ok' "would grant NT SERVICE\LocalNotify Modify on $dir"
            } else {
                $grant = Invoke-Native -Exe (Join-Path $env:SystemRoot 'System32\icacls.exe') -Arguments @($dir, '/grant', 'NT SERVICE\LocalNotify:(OI)(CI)M') -TimeoutSec 60
                if ($grant.Code -ne 0) { throw "icacls exit $($grant.Code): $(First-Line ($grant.Out + $grant.Err))" }
                Add-Result 'study mailbox' 'ok' "granted NT SERVICE\LocalNotify Modify on $dir"
            }
        } catch {
            Add-Result 'study mailbox' 'failed' "$dir : $($_.Exception.Message)"
        }
    }
}

