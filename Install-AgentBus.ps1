            $fb = Invoke-Helper @('fallback', $settings, 'remove', $Root, (Dry), $BackupDir, $label)
            if ($fb.removed) { $steps += "$(if ($DryRun) { 'would remove' } else { 'removed' }) $($fb.removed) fallback hook(s)" }
            $skillState = Remove-SkillDir $fallbackSkill "$label-agent-bus-skill"
            if ($skillState -ne 'not present') { $steps += "fallback skill $skillState" }
            Add-Result $label 'ok' $(if ($steps.Count) { $steps -join '; ' } else { 'nothing installed' })
        } catch {
            Add-Result $label 'failed' $_.Exception.Message
        }
        continue
    }
    $pluginError = $null
    $steps = @()
    try {
        if (-not $script:Claude) { throw 'claude CLI not found on PATH' }
        $markets = Get-ClaudeJson $childConfig @('plugin', 'marketplace', 'list', '--json')
        if (-not @($markets | Where-Object { $_.name -eq $MarketName }).Count) {
            if ($DryRun) { $steps += 'would add marketplace' }
            else { Backup-File $settings "$label-settings"; Invoke-ClaudeStep $childConfig @('plugin', 'marketplace', 'add', $PluginRoot); $steps += 'marketplace added' }
        }
        $plugins = Get-ClaudeJson $childConfig @('plugin', 'list', '--json')
        $entry = @($plugins | Where-Object { $_.id -eq $PluginId }) | Select-Object -First 1
        if (-not $entry) {
            if ($DryRun) { $steps += 'would install plugin' }
            else {
                Backup-File $settings "$label-settings"
                Invoke-ClaudeStep $childConfig @('plugin', 'install', $PluginId, '--scope', 'user')
                $check = @(Get-ClaudeJson $childConfig @('plugin', 'list', '--json') | Where-Object { $_.id -eq $PluginId })
                if (-not $check.Count) { throw 'plugin install reported success but the plugin is not listed' }
                $steps += 'plugin installed'
            }
        } elseif (-not $entry.enabled) {
            if ($DryRun) { $steps += 'would enable plugin' }
            else { Backup-File $settings "$label-settings"; Invoke-ClaudeStep $childConfig @('plugin', 'enable', $PluginId, '--scope', 'user'); $steps += 'plugin enabled' }
        } else {
            $steps += 'plugin already installed'
        }
    } catch {
        $pluginError = $_.Exception.Message
    }
    try {
        if ($null -eq $pluginError) {
            # The plugin provides the hooks now: drop any hooks a previous fallback merged into settings.json.
            $fb = Invoke-Helper @('fallback', $settings, 'remove', $Root, (Dry), $BackupDir, $label)
            if ($fb.removed) { $steps += "$(if ($DryRun) { 'would remove' } else { 'removed' }) $($fb.removed) old fallback hook(s)" }
            $skillState = Remove-SkillDir $fallbackSkill "$label-agent-bus-skill"
            if ($skillState -ne 'not present') { $steps += "fallback skill $skillState" }
        } else {
            $skillState = Copy-Skill (Join-Path $PluginDir 'skills\agent-bus\SKILL.md') $fallbackSkill "$label-agent-bus-skill"
            $fb = Invoke-Helper @('fallback', $settings, 'add', $Root, (Dry), $BackupDir, $label)
            $steps += "skill $skillState"
            $steps += $(if ($fb.changed) { "$(if ($DryRun) { 'would merge' } else { 'merged' }) plugin hooks into settings.json" } else { 'hooks already in settings.json' })
        }
        $allow = Invoke-Helper @('allow-http', $settings, [string]$Port, (Dry), $BackupDir, $label)
        if ($allow.changed) { $steps += "$(if ($DryRun) { 'would add' } else { 'added' }) http://127.0.0.1:$Port/** to allowedHttpHookUrls" }
        if ($null -eq $pluginError) { Add-Result $label 'ok' ($steps -join '; ') }
        else { Add-Result $label 'fallback' ("plugin not installed ($pluginError); " + ($steps -join '; ') + '; no bus_* MCP tools here, the CLI works') }
    } catch {
        $why = if ($pluginError) { "plugin: $pluginError; fallback: " } else { '' }
        Add-Result $label 'failed' ($why + $_.Exception.Message)
    }
}
