<#
.SYNOPSIS
  Installs (or with -Remove uninstalls) the Agent Bus clients for every Claude config dir, Codex and the Claude desktop app.

.DESCRIPTION
  - Regenerates plugin\agent-bus\hooks\hooks.json, .mcp.json and the slash commands with this machine's Python path,
    project path and service port, and mirrors skills\agent-bus\SKILL.md into the plugin.
  - For every ~\.claude* dir that has settings.json or .claude.json: registers the local marketplace
    (plugin\) and installs agent-bus@agent-bus-local at user scope with the claude CLI (CLAUDE_CONFIG_DIR is set only
    in the child process environment, never in your session). If that fails it falls back to copying the skill into
    <config>\skills and merging the plugin hooks into <config>\settings.json (reported as "fallback").
  - Removes the old automatic Stop/Notification phone hooks (python notify.py hooks remove).
  - Installs the agent-bus and updated notify-user skills into ~\.codex\skills (and refreshes existing notify-user copies).
  - Adds the agent-bus MCP server to the Claude desktop app config (APPDATA and the MSIX package path).
  - Grants NT SERVICE\LocalNotify Modify on the study mailbox dir(s) from config.
  Idempotent. Backs up every file it edits to data\backups. Never starts, stops or kills any process; running
  sessions pick the plugin up after a restart or /reload-plugins.

.PARAMETER Remove   Uninstall: plugin + marketplace, fallback hooks/skills, Codex agent-bus skill, desktop MCP entry.
.PARAMETER DryRun   Report what would change without changing anything (read-only claude CLI calls still run).
.PARAMETER Python   Python executable to use (default: the first python on PATH that is not the WindowsApps stub).

.EXAMPLE
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\Install-AgentBus.ps1 -DryRun
#>
