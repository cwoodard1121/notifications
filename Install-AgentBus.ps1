import copy, glob, json, os, re, shutil, sys, time

HOOK_URL = re.compile(r"^http://(127\.0\.0\.1|localhost):\d+/hooks/claude$")
DESCRIPTION = ("Agent Bus: join on SessionStart (command bridge), deliver bus messages on UserPromptSubmit/PreToolUse, "
               "go idle on Stop (plus the experimental idle re-wake), leave on SessionEnd. Generated by Install-AgentBus.ps1.")


def out(**result):
    print(json.dumps(result, ensure_ascii=True))


def read_json(path):
    with open(path, "rb") as handle:
        raw = handle.read()
    text = raw.decode("utf-8-sig")
    return (json.loads(text) if text.strip() else {}), raw.startswith(b"\xef\xbb\xbf")


def write_text(path, text, dry, backup_dir=None, label=None):
    if dry:
        return
    if backup_dir and os.path.exists(path):
        os.makedirs(backup_dir, exist_ok=True)
        name = "agentbus-%s-%s-%s" % (label or "file", time.strftime("%Y%m%d-%H%M%S"), os.path.basename(path))
        shutil.copy2(path, os.path.join(backup_dir, name))
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".agentbus.tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    os.replace(tmp, path)


def dump(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def config(root):
    example, cfg = {}, {}
    try:
        example = read_json(os.path.join(root, "config.example.json"))[0]
    except (OSError, ValueError):
        pass
    try:
        cfg = read_json(os.environ.get("NOTIFY_CONFIG") or os.path.join(root, "config.json"))[0]
    except (OSError, ValueError):
        pass
    port = cfg.get("port") if type(cfg.get("port")) is int else example.get("port", 8765)
    mailbox = dict(((example.get("bus") or {}).get("mailbox")) or {})
    mailbox.update(((cfg.get("bus") or {}).get("mailbox")) or {})
    return {"port": port, "token": cfg.get("api_token") or "", "mailbox": mailbox}


def quote(path):
    return '"%s"' % path if " " in path else path


def op_info(root):
    cfg = config(root)
    mb = cfg["mailbox"]
    out(ok=True, python=sys.executable, version=list(sys.version_info[:3]), port=cfg["port"], token_set=bool(cfg["token"]),
        mailbox_enabled=bool(mb.get("enabled")), mailbox_dirs=[d for d in (mb.get("dirs") or []) if isinstance(d, str)])


def op_gen(root, python, dry):
    cfg = config(root)
    root_fs, py_fs = root.replace("\\", "/").rstrip("/"), python.replace("\\", "/")
    plugin = os.path.join(root, "plugin", "agent-bus")
    changed = []
    url = "http://127.0.0.1:%d/hooks/claude" % cfg["port"]

    def http(timeout):
        hook = {"type": "http", "url": url, "timeout": timeout}
        if cfg["token"]:
            hook["headers"] = {"Authorization": "Bearer " + cfg["token"]}
        return hook

    command = '"%s" "%s/bus.py"' % (py_fs, root_fs)
    hooks = {"description": DESCRIPTION, "hooks": {
        "SessionStart": [{"hooks": [{"type": "command", "command": command + " hook", "timeout": 5}]}],
        "UserPromptSubmit": [{"hooks": [http(3)]}],
        "PreToolUse": [{"matcher": "*", "hooks": [http(3)]}],
        "Stop": [{"hooks": [http(3)]},
                 {"hooks": [{"type": "command", "command": command + " rewake", "async": True, "asyncRewake": True,
                             "timeout": 43200}]}],
        "SessionEnd": [{"hooks": [http(1)]}]}}
    mcp_path = os.path.join(plugin, ".mcp.json")
    old_prefix = None
    try:
        server = read_json(mcp_path)[0]["mcpServers"]["agent-bus"]
        old_prefix = quote(server["command"]) + " " + quote(os.path.dirname(server["args"][0]).replace("\\", "/") + "/bus.py")
    except (OSError, ValueError, KeyError, IndexError, TypeError):
        pass
    mcp = {"mcpServers": {"agent-bus": {"command": py_fs, "args": [root_fs + "/bus_mcp.py", "--client", "claude-code"]}}}
    targets = [(os.path.join(plugin, "hooks", "hooks.json"), dump(hooks)), (mcp_path, dump(mcp))]
    # Slash commands carry "<python> <root>/bus.py" (allowed-tools rule + the command itself): swap in the new prefix.
    new_prefix = quote(py_fs) + " " + quote(root_fs + "/bus.py")
    pattern = re.compile(r'(?:"[^"\n]*python[^"\n]*"|[^\s"`(]*python[^\s"`]*) (?:"[^"\n]*/bus\.py"|[^\s"`]*/bus\.py)', re.I)
    for path in sorted(glob.glob(os.path.join(plugin, "commands", "*.md"))):
        with open(path, encoding="utf-8-sig") as handle:
            text = handle.read()
        new = text.replace(old_prefix, new_prefix) if old_prefix and old_prefix in text else pattern.sub(lambda m: new_prefix, text)
        targets.append((path, new))
    skill_src = os.path.join(root, "skills", "agent-bus", "SKILL.md")
    if os.path.exists(skill_src):
        with open(skill_src, encoding="utf-8-sig") as handle:
            targets.append((os.path.join(plugin, "skills", "agent-bus", "SKILL.md"), handle.read()))
    for path, text in targets:
        try:
            with open(path, encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current != text:
            changed.append(os.path.relpath(path, root))
            write_text(path, text, dry)
    out(ok=True, changed=changed, port=cfg["port"], token_in_hooks=bool(cfg["token"]))


def op_desktop(path, action, python, root, dry, backup_dir):
    exists = os.path.exists(path)
    data, bom = read_json(path) if exists else ({}, False)
    if not isinstance(data, dict):
        raise ValueError("not a JSON object")
    before = json.dumps(data, sort_keys=True)
    servers = data.get("mcpServers") if isinstance(data.get("mcpServers"), dict) else {}
    entry = {"command": python.replace("\\", "/"),
             "args": [root.replace("\\", "/").rstrip("/") + "/bus_mcp.py", "--client", "claude-desktop"]}
    if action == "add":
        servers["agent-bus"] = entry
        data["mcpServers"] = servers
    else:
        servers.pop("agent-bus", None)
        if servers:
            data["mcpServers"] = servers
        else:
            data.pop("mcpServers", None)
    changed = json.dumps(data, sort_keys=True) != before and (exists or action == "add")
    if changed:
        write_text(path, dump(data), dry, backup_dir, "claude-desktop")
    out(ok=True, changed=changed, created=changed and not exists, had_bom=bom, servers=sorted(servers))


def ours(hook):
    command = str(hook.get("command") or "").replace("\\", "/")
    return (bool(re.search(r"/bus\.py\"?\s+(hook|rewake)\b", command)) or bool(HOOK_URL.match(str(hook.get("url") or ""))))


def op_fallback(settings, action, root, dry, backup_dir, label):
    exists = os.path.exists(settings)
    data = read_json(settings)[0] if exists else {}
    if not isinstance(data, dict):
        raise ValueError("settings.json is not a JSON object")
    before = json.dumps(data, sort_keys=True)
    hooks = data.get("hooks") if isinstance(data.get("hooks"), dict) else {}
    removed = 0
    for event in list(hooks):
        groups, kept = hooks[event] if isinstance(hooks[event], list) else [], []
        for group in groups:
            inner = group.get("hooks") if isinstance(group, dict) else None
            if not isinstance(inner, list):
                kept.append(group)
                continue
            mine = [h for h in inner if isinstance(h, dict) and ours(h)]
            removed += len(mine)
            rest = [h for h in inner if h not in mine]
            if rest:
                kept.append(dict(group, hooks=rest))
        if kept:
            hooks[event] = kept
        else:
            hooks.pop(event)
    if action == "add":
        plugin_hooks = read_json(os.path.join(root, "plugin", "agent-bus", "hooks", "hooks.json"))[0]["hooks"]
        for event, groups in plugin_hooks.items():
            hooks.setdefault(event, []).extend(copy.deepcopy(groups))
    if hooks:
        data["hooks"] = hooks
    else:
        data.pop("hooks", None)
    changed = json.dumps(data, sort_keys=True) != before
    if changed:
        write_text(settings, dump(data), dry, backup_dir, label + "-settings")
    out(ok=True, changed=changed, removed=removed, present=removed > 0)


def op_allow_http(settings, port, dry, backup_dir, label):
    if not os.path.exists(settings):
        return out(ok=True, present=False, changed=False)
    data = read_json(settings)[0]
    allowed = data.get("allowedHttpHookUrls") if isinstance(data, dict) else None
    if not isinstance(allowed, list):
        return out(ok=True, present=False, changed=False)
    pattern = "http://127.0.0.1:%s/**" % port
    if pattern in allowed:
        return out(ok=True, present=True, changed=False)
    allowed.append(pattern)
    write_text(settings, dump(data), dry, backup_dir, label + "-settings")
    out(ok=True, present=True, changed=True)


def op_old_hooks(settings):
    count = 0
    if os.path.exists(settings):
        data = read_json(settings)[0]
        for groups in ((data.get("hooks") or {}) if isinstance(data, dict) else {}).values():
            for group in groups if isinstance(groups, list) else []:
                for hook in (group.get("hooks") or []) if isinstance(group, dict) else []:
                    if isinstance(hook, dict) and re.search(r"notify\.py\"?\s+hook\s+claude", str(hook.get("command") or "")):
                        count += 1
    out(ok=True, count=count)


def main():
    op, args = sys.argv[1], sys.argv[2:]
    try:
        if op == "info":
            op_info(args[0])
        elif op == "gen":
            op_gen(args[0], args[1], args[2] == "1")
        elif op == "desktop":
            op_desktop(args[0], args[1], args[2], args[3], args[4] == "1", args[5])
        elif op == "fallback":
            op_fallback(args[0], args[1], args[2], args[3] == "1", args[4], args[5])
        elif op == "allow-http":
            op_allow_http(args[0], args[1], args[2] == "1", args[3], args[4])
        elif op == "old-hooks":
            op_old_hooks(args[0])
        else:
            out(ok=False, error="unknown op " + op)
    except Exception as exc:
        out(ok=False, error="%s: %s" % (exc.__class__.__name__, exc))


main()
